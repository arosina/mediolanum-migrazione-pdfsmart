	/********************************************************************************/
	/********************************************************************************/
	public AbstractTypePropertyDescriptor[] addMappedPropertyDescriptors(AbstractTypePropertyDescriptor[] props) throws Exception{
		
		int pdCount=0;
		Set keys = fields.keySet();		
		AbstractTypePropertyDescriptor[] result = new AbstractTypePropertyDescriptor[keys.size()+props.length];
		
    	Iterator it = keys.iterator();
    	while(it.hasNext()){
    		String fieldName = (String)it.next();
    		AbstractType fieldValue = (AbstractType)fields.get(fieldName); 
    		AbstractTypePropertyDescriptor p = new AbstractTypePropertyDescriptor(fieldName,fieldValue,pdCount);
    		result[pdCount] = p;
    		pdCount++;
    	}
    	
		for(int i=0;i<props.length;i++,pdCount++)
			result[pdCount] = props[i];
		
    	return result;
	}
	
	/********************************************************************************/
	/********************************************************************************/
	public AbstractTypePropertyDescriptor[] getMappedPropertyDescriptors() throws Exception{
		
		AbstractTypePropertyDescriptor[] result = new AbstractTypePropertyDescriptor[fieldsOrder.size()];
		for(int i=0;i<fieldsOrder.size();i++){
			String fieldName = (String)fieldsOrder.get(i);
    		AbstractType fieldValue = (AbstractType)fields.get(fieldName); 
    		AbstractTypePropertyDescriptor p = new AbstractTypePropertyDescriptor(fieldName,fieldValue,i);
    		result[i] = p;			
		}
    	return result;
	}
	
	/********************************************************************************/
	/********************************************************************************/
	public AbstractTypePropertyDescriptor getMappedPropertyDescriptor(String propName, AbstractTypePropertyDescriptor prop){
		if(prop != null)
			return prop;
		Integer fieldIndex = (Integer)fieldsIndex.get(propName);
		if(fieldIndex == null)
			return null;
		AbstractType fieldValue = (AbstractType)fields.get(propName);
		if(fieldValue == null)
			return null;
		AbstractTypePropertyDescriptor p = new AbstractTypePropertyDescriptor(propName,fieldValue,fieldIndex.intValue());
		return p;
	}
	
	/********************************************************************************/
	/********************************************************************************/
	public void addProperty(String name, AbstractType value){
		if(fields.containsKey(name)){
			fields.put(name,value);
			return;
		}
		Integer fieldIndex = new Integer(fields.keySet().size());
		fieldsOrder.add(name);
		fields.put(name,value);
		fieldsMethods.put("ff"+fieldIndex,name);
		fieldsIndex.put(name,fieldIndex);
	}
	
	/********************************************************************************/
	/********************************************************************************/
	public AbstractType readProperty(String name){
		return (AbstractType)fields.get(name);
	}
	
	/********************************************************************************/
	/********************************************************************************/
	public void writeProperty(String name, AbstractType value){
		fields.put(name,value);
	}

	/********************************************************************************/
	/********************************************************************************/
	private AbstractType readField(String fieldMethod){
		String fieldName = (String)fieldsMethods.get(fieldMethod);
		return (AbstractType)fields.get(fieldName);
	}
	
	/********************************************************************************/
	/********************************************************************************/
	private void writeField(String fieldMethod, AbstractType value){
		String fieldName = (String)fieldsMethods.get(fieldMethod);
		fields.put(fieldName,value);
	}
	
	/********************************************************************************/
	/********************************************************************************/
	public void clearMappedProperties(){
		fieldsMethods 	= new HashMap();	
		fieldsIndex    	= new HashMap();	
		fields 		  	= new HashMap();
		fieldsOrder		= new Vector();
	}
	
