package com.atosorigin.wfem.htmltopdf;

import java.awt.Color;

/** ************************************************************************************************
 * @author: Ricotti Corrado
************************************************************************************************ **/
public class ControllerAttributes {

	public static final int ALIGN_CENTER = 0;
	public static final int ALIGN_LEFT   = 1;
	public static final int ALIGN_RIGHT  = 2;
	
	public static final int ALIGN_MIDDLE  = 0;
	public static final int ALIGN_TOP     = 1;
	public static final int ALIGN_BOTTOM  = 2;
	
	private int border = -1;

	private int colSpan = 1;
	private boolean noWrap = false;
	private int width = 0;
	private int height = 0;
	private int align = ALIGN_LEFT;
	private int valign = ALIGN_MIDDLE;

	private Color background = null;
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public ControllerAttributes() {
		super();
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public String getUniqueKey(){
		String result = ""+align;
		if(background != null)
			result += background.getRGB();
		return result;
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public int getAlign() {
		return align;
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public java.awt.Color getBackground() {
		return background;
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public int getBorder() {
		return border;
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public int getColSpan() {
		return colSpan;
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public int getHeight() {
		return height;
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public int getWidth() {
		return width;
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public void setAlign(int newAlign) {
		align = newAlign;
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public void setBackground(java.awt.Color newBackground) {
		background = newBackground;
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public void setBorder(int newBorder) {
		border = newBorder;
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public void setColSpan(int newColSpan) {
		colSpan = newColSpan;
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public void setHeight(int newHeight) {
		height = newHeight;
	}
	
	/**************************************************************************************************/
	/**************************************************************************************************/
	public void setWidth(int newWidth) {
		width = newWidth;
	}

	/**************************************************************************************************/
	/**************************************************************************************************/
	public int getValign() {
		return valign;
	}

	/**************************************************************************************************/
	/**************************************************************************************************/
	public void setValign(int valign) {
		this.valign = valign;
	}

	/**************************************************************************************************/
	/**************************************************************************************************/
	public boolean isNoWrap() {
		return noWrap;
	}
	/**************************************************************************************************/
	/**************************************************************************************************/

	public void setNoWrap(boolean noWrap) {
		this.noWrap = noWrap;
	}


}
