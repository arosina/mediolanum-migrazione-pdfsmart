package com.atosorigin.wfem.dao.exceptions;

import java.sql.SQLException;

/**
 * Insert the type's description here.
 * Creation date: (06/11/2002 13.02.52)
 * @author: Administrator
 */
public class DAOException extends Throwable{

	private String descr;
	private int errorCode;
	
	/*************************************************************************/
	/*************************************************************************/
	public DAOException() {
		super();
	}
	
	/*************************************************************************/
	/*************************************************************************/
	public DAOException(SQLException sqle) {
		super();
		setSqlException(sqle);
	}
	
	/*************************************************************************/
	/*************************************************************************/
	public DAOException(String descr) {
		super();
		this.descr = descr;
	}
	
	/*************************************************************************/
	/*************************************************************************/
	public int getErrorCode() {
		return errorCode;
	}
	
	/*************************************************************************/
	/*************************************************************************/
	public String toString() {
		return descr;
	}
	
	/*************************************************************************/
	/*************************************************************************/
	public String getMessage() {
		return descr;
	}
	
	/*************************************************************************/
	/*************************************************************************/
	public void setSqlException(SQLException sqle) {
		this.descr = sqle.toString();
		this.errorCode = sqle.getErrorCode();
	}

	/*************************************************************************/
	/*************************************************************************/
	public String getDescr() {
		return descr;
	}

	/*************************************************************************/
	/*************************************************************************/
	public void setDescr(String descr) {
		this.descr = descr;
	}

}
