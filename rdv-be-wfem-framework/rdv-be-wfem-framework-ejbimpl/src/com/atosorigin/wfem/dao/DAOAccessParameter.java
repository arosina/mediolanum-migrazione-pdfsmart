package com.atosorigin.wfem.dao;

import java.io.Serializable;

/*************************************************************************************************/
/*************************************************************************************************/
public class DAOAccessParameter implements Serializable{
	
	public final static int NORMAL_FIELD         = 0;
	public final static int READONLY_FIELD       = 1;
	public final static int READONLYIFNULL_FIELD = 2;

	private int fieldType = NORMAL_FIELD;
	private String propertyName;
	private String propertyValue;
	private String propertyType;
	private String dbColumnName;
	private String notNullValue;
	private boolean primaryKey = false;
	private String  foreignKey;
	private boolean concurrencyField = false;

	private boolean disabled = false;

	// For FileType management
	public final static String FILETYPE_IMAGE_DATA = "image";
	public final static String FILETYPE_CONTENTTYPE_DATA = "contentType";
	public final static String FILETYPE_FILENAME_DATA = "fileName";
	public final static String FILETYPE_IMAGE_IS_VIRUS_EXAMINED = "virusExamined";
	private String fileTypeDataPart;
	
	/*************************************************************************************************/
	/*************************************************************************************************/
	public DAOAccessParameter() {
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public java.lang.String getDbColumnName() {
		return dbColumnName;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public int getFieldType() {
		return fieldType;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public java.lang.String getNotNullValue() {
		return notNullValue;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public java.lang.String getPropertyName() {
		return propertyName;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public boolean isConcurrencyField() {
		return concurrencyField;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public boolean isPrimaryKey() {
		return primaryKey;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public boolean isReadonly() {
		return (fieldType == READONLY_FIELD ? true : false);
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public boolean isReadonlyIfNull() {
		return (fieldType == READONLYIFNULL_FIELD ? true : false);
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public void setConcurrencyField(boolean newConcurrencyField) {
		concurrencyField = newConcurrencyField;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public void setDbColumnName(java.lang.String newDbColumnName) {
		dbColumnName = newDbColumnName;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public void setFieldType(int newFieldType) {
		fieldType = newFieldType;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public void setNotNullValue(java.lang.String newNotNullValue) {
		notNullValue = newNotNullValue;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public void setPrimaryKey(boolean newPrimaryKey) {
		primaryKey = newPrimaryKey;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public void setPropertyName(java.lang.String newPropertyName) {
		propertyName = newPropertyName;
	}
	
	/*************************************************************************************************/
	/*************************************************************************************************/
	public String getPropertyValue() {
		return propertyValue;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public void setPropertyValue(String propertyValue) {
		this.propertyValue = propertyValue;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public String getPropertyType() {
		return propertyType;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public void setPropertyType(String propertyType) {
		this.propertyType = propertyType;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
    public String getForeignKey() {
        return foreignKey;
    }

    /*************************************************************************************************/
	/*************************************************************************************************/
    public void setForeignKey(String foreignKey) {
        this.foreignKey = foreignKey;
    }

    /*************************************************************************************************/
	/*************************************************************************************************/
    public boolean isDisabled() {
        return disabled;
    }

    /*************************************************************************************************/
	/*************************************************************************************************/
    public void setDisabled(boolean disabled) {
        this.disabled = disabled;
    }

    /*************************************************************************************************/
	/*************************************************************************************************/
	public String getFileTypeDataPart() {
		return fileTypeDataPart;
	}

    /*************************************************************************************************/
	/*************************************************************************************************/
	public void setFileTypeDataPart(String fileTypeDataPart) {
		this.fileTypeDataPart = fileTypeDataPart;
	}

}
