package com.atosorigin.wfem.dao;

import com.atosorigin.wfem.types.IntegerType;
import com.atosorigin.wfem.types.ListType;
/*************************************************************************************************/
/*************************************************************************************************/
public class DAOTableResultModel extends DAOBaseResultModel{
	private IntegerType result = new IntegerType();
	private ListType childs = new ListType();
	private ListType all = new ListType();
	
	/*************************************************************************************************/
	/*************************************************************************************************/
	public DAOTableResultModel() {
		super();
	}
	
	/*************************************************************************************************/
	/*************************************************************************************************/
	public com.atosorigin.wfem.types.IntegerType getResult() {
		return result;
	}
	
	/*************************************************************************************************/
	/*************************************************************************************************/
	protected void setResult(com.atosorigin.wfem.types.IntegerType newResult) {
		result = newResult;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public ListType getAll() {
		return all;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public ListType getChilds() {
		return childs;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public void setAll(ListType all) {
		this.all = all;
	}

	/*************************************************************************************************/
	/*************************************************************************************************/
	public void setChilds(ListType childs) {
		this.childs = childs;
	}

}
